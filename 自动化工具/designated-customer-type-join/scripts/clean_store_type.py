def _norm(v):
    """单值归一化：NaN/空 -> ''，其余去空白转字符串（用于关联键与去重键）。"""
    if pd.isna(v):
        return ""
    s = str(v).strip()
    return s


# 布尔型判断字段（数据里取值 1/1.0/是 或 0/0.0/否）
BOOL_FIELDS = {"是否生鲜主导", "是否大宗售卖", "城市总部是否连锁", "营业时间超16小时", "进口产品SKU超40"}


def _bool(v):
    """布尔字段归一化：1/1.0/是 -> '是'，0/0.0/否 -> '否'，空/未知 -> ''。"""
    s = _norm(v)
    if s in ("1", "1.0", "是", "true", "True", "yes", "Y", "y"):
        return "是"
    if s in ("0", "0.0", "否", "false", "False", "no", "N", "n"):
        return "否"
    return ""


def _chain(v):
    """连锁字段归一化：1/是 -> '是'；0/否/空 -> '否'（连锁=空等同非连锁）。"""
    s = _norm(v)
    if s in ("1", "1.0", "是", "true", "True", "yes", "Y", "y"):
        return "是"
    return "否"  # 0/否/空 一律视为非连锁


def _chain_num(v):
    """连锁字段值级归一化（输出数值）：1/是 -> 1；0/否/空 -> 0（连锁=空等同非连锁）。"""
    s = _norm(v)
    if s in ("1", "1.0", "是", "true", "True", "yes", "Y", "y"):
        return 1
    return 0


